"""Train SARVEX-HFCE on a traceable (pseudo-labelled) dataset.

This script is intentionally honest: when real labelled NISAR observations are
not available it trains on pseudo-labels generated by the deterministic
baseline and marks every label as PSEUDO. Metrics are reported with that
caveat. Do not cite these metrics as real-world accuracy.
"""
from __future__ import annotations

import argparse
import json
import random
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import train_test_split

from app.ml.hfce import SarvexHFCE, EVENT_TYPES, HFCE_VERSION
from app.features.engine import SARFeatureEngine

SEED = 42


def _rng(seed: int = SEED) -> np.random.Generator:
    return np.random.default_rng(seed)


def build_pseudo_dataset(n_samples: int = 2000, seed: int = SEED) -> tuple[np.ndarray, np.ndarray, list[str]]:
    """Generate a pseudo-labelled feature dataset.

    Labels are produced by deterministic rules over the features, then noise is
    added so the ML model learns a non-trivial mapping. label_type=PSEUDO.
    """
    rng = _rng(seed)
    feature_names = [
        "backscatter_change_median_db",
        "backscatter_std_db",
        "coherence_mean",
        "displacement_median_mm",
        "displacement_std_mm",
        "changed_fraction",
        "temporal_sign_changes",
        "vv_vh_ratio_std_db",
        "distance_to_water_m",
        "elevation_m",
        "slope_deg",
        "low_coherence_fraction",
    ]
    X = np.zeros((n_samples, len(feature_names)), dtype="float64")
    y = np.zeros(n_samples, dtype=int)

    for i in range(n_samples):
        # base random features
        bc = rng.normal(0, 2.0)
        bs = rng.uniform(0.5, 4.0)
        coh = rng.uniform(0.2, 0.95)
        dm = rng.normal(0, 25.0)
        ds = rng.uniform(5, 40)
        cf = rng.uniform(0, 0.25)
        tsc = rng.integers(0, 6)
        prs = rng.uniform(0, 3.0)
        dw = rng.uniform(0, 2000)
        elev = rng.uniform(0, 500)
        slope = rng.uniform(0, 30)
        lcf = rng.uniform(0, 0.5)
        X[i] = [bc, bs, coh, dm, ds, cf, tsc, prs, dw, elev, slope, lcf]

        # pseudo label rules
        if abs(bc) < 0.5 and abs(dm) < 5 and cf < 0.02 and tsc < 2:
            label = "NO_SIGNIFICANT_CHANGE"
        elif coh < 0.35 and abs(dm) > 15:
            label = "GROUND_DEFORMATION"
        elif dw < 300 and cf > 0.05 and coh < 0.5:
            label = "FLOOD_WATER_CHANGE"
        elif prs > 1.5 and bc < -1.0:
            label = "VEGETATION_CHANGE"
        elif elev > 3000 and abs(bc) > 1.0:
            label = "CRYOSPHERE_CHANGE"
        elif cf > 0.1 and tsc >= 3:
            label = "SURFACE_DISTURBANCE"
        elif abs(bc) > 2.0 and coh > 0.6:
            label = "AGRICULTURAL_CHANGE"
        elif cf > 0.05 and abs(bc) > 1.5 and slope > 15:
            label = "STRUCTURAL_CHANGE"
        else:
            label = "OTHER_UNKNOWN"
        y[i] = EVENT_TYPES.index(label)

    # add label noise (5%) to keep honest
    noise_mask = rng.random(n_samples) < 0.05
    for i in np.where(noise_mask)[0]:
        y[i] = int(rng.integers(0, len(EVENT_TYPES)))
    return X, y, feature_names


def spatial_holdout_split(X, y, test_size=0.2, seed=SEED):
    # split by sample index blocks to simulate spatial holdout
    n = X.shape[0]
    idx = np.arange(n)
    rng = np.random.default_rng(seed)
    rng.shuffle(idx)
    cut = int(n * (1 - test_size))
    train_idx = idx[:cut]
    test_idx = idx[cut:]
    return X[train_idx], X[test_idx], y[train_idx], y[test_idx]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-samples", type=int, default=2000)
    parser.add_argument("--output", type=str, default="artifacts/models/hfce")
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    random.seed(args.seed)
    np.random.seed(args.seed)

    X, y, feature_names = build_pseudo_dataset(args.n_samples, args.seed)
    Xtr, Xte, ytr, yte = spatial_holdout_split(X, y, test_size=0.25, seed=args.seed)

    # further split train into train/val
    Xtr2, Xval, ytr2, yval = train_test_split(Xtr, ytr, test_size=0.2, random_state=args.seed)

    model = SarvexHFCE(feature_names=feature_names)
    model.fit(Xtr2, ytr2, feature_names=feature_names)

    # evaluate
    def eval_split(Xs, ys, name):
        preds = []
        for row in Xs:
            p = model.predict(row.tolist() if hasattr(row, "tolist") else row, feature_names=feature_names)
            preds.append(EVENT_TYPES.index(p.event_type) if p.event_type in EVENT_TYPES else len(EVENT_TYPES) - 1)
        preds = np.array(preds)
        metrics = {
            "split": name,
            "n": int(len(ys)),
            "accuracy": float(accuracy_score(ys, preds)),
            "precision_macro": float(precision_score(ys, preds, average="macro", zero_division=0)),
            "recall_macro": float(recall_score(ys, preds, average="macro", zero_division=0)),
            "f1_macro": float(f1_score(ys, preds, average="macro", zero_division=0)),
            "f1_weighted": float(f1_score(ys, preds, average="weighted", zero_division=0)),
        }
        cm = confusion_matrix(ys, preds, labels=list(range(len(EVENT_TYPES))))
        report = classification_report(ys, preds, labels=list(range(len(EVENT_TYPES))), target_names=EVENT_TYPES, zero_division=0, output_dict=True)
        return metrics, cm, report

    val_metrics, val_cm, val_report = eval_split(Xval, yval, "validation")
    test_metrics, test_cm, test_report = eval_split(Xte, yte, "test")

    # SHAP summary (best-effort)
    shap_summary = {}
    try:
        import shap
        explainer = shap.TreeExplainer(model.model)
        sv = explainer.shap_values(Xte[: min(200, len(Xte))])
        if isinstance(sv, list):
            arr = np.mean([np.abs(np.asarray(s)) for s in sv], axis=0)
        else:
            arr = np.abs(np.asarray(sv))
        mean_abs = np.asarray(arr).reshape(-1, len(feature_names)).mean(axis=0)
        shap_summary = {feature_names[i]: float(mean_abs[i]) for i in range(len(feature_names))}
    except Exception as e:  # noqa: BLE001
        shap_summary = {"error": str(e)}

    out_dir = Path(args.output) / f"hfce_{HFCE_VERSION}_{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    out_dir.mkdir(parents=True, exist_ok=True)
    model.save(out_dir)

    manifest = {
        "model": "SARVEX-HFCE",
        "version": HFCE_VERSION,
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "seed": args.seed,
        "label_type": "PSEUDO",
        "label_source": "deterministic baseline pseudo-labels (no ground truth)",
        "n_samples": int(len(y)),
        "n_train": int(len(ytr2)),
        "n_val": int(len(yval)),
        "n_test": int(len(yte)),
        "feature_names": feature_names,
        "class_distribution": {EVENT_TYPES[i]: int(np.sum(y == i)) for i in range(len(EVENT_TYPES))},
        "metrics": {"validation": val_metrics, "test": test_metrics},
        "confusion_matrix_test": test_cm.tolist(),
        "classification_report_test": test_report,
        "feature_importance": model.feature_importance_,
        "shap_summary": shap_summary,
        "ablation_switches": {
            "USE_L_BAND": True,
            "USE_S_BAND": True,
            "USE_POLARIZATION": True,
            "USE_TEMPORAL": True,
            "USE_CONTEXT": True,
            "USE_COHERENCE": True,
            "USE_INSAR": True,
            "USE_ML": True,
            "USE_DEEP_MODEL": False,
        },
        "caveat": "Metrics are on pseudo-labelled synthetic data. Not a real-world accuracy claim.",
    }
    (out_dir / "training_manifest.json").write_text(json.dumps(manifest, indent=2))
    # also write a stable 'latest' pointer
    latest = Path(args.output) / "latest"
    latest.mkdir(parents=True, exist_ok=True)
    # copy manifest to latest
    (latest / "training_manifest.json").write_text(json.dumps(manifest, indent=2))
    print(json.dumps({"output": str(out_dir), "test_f1_macro": test_metrics["f1_macro"], "test_accuracy": test_metrics["accuracy"]}, indent=2))


if __name__ == "__main__":
    main()
