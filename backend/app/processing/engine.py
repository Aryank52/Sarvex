"""SAR processing engine: job state machine, reproducibility and persistence.

State sequence:
QUEUED -> VALIDATING -> DOWNLOADING -> PREPROCESSING -> PROCESSING ->
ANALYZING -> POSTPROCESSING -> COMPLETED (or FAILED / CANCELLED).

Every transition is logged with a correlation ID. Measurements, events,
timeseries, confidence and provenance are persisted before any explanation is
generated by the copilot layer.
"""
from __future__ import annotations

import logging
import traceback
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from app.config import get_settings
from app.core.provenance import build_provenance, utcnow
from app.db.models import (
    AOI,
    AnalysisResult,
    AuditLog,
    ChangeMap,
    ConfidenceScore,
    Dataset,
    Observation,
    ProcessingJob,
    ProcessingRun,
    Product,
    SARFeature,
    TimeSeries,
    UncertaintyEstimate,
)
from app.db.session import session_scope
from app.events.context import compute_exposures, correlate_event_context
from app.events.engine import build_events
from app.isce3.adapter import get_isce3_adapter
from app.logging_config import correlation_id_var
from app.processing import PROCESSORS
from app.processing.base import InputProduct, ProcessContext
from app.storage.object_store import get_object_store

logger = logging.getLogger("sarvex.processing")

TERMINAL_STATES = {"COMPLETED", "FAILED", "CANCELLED"}
PROGRESS = {
    "QUEUED": 0.0,
    "CLAIMED": 2.0,
    "VALIDATING": 8.0,
    "DOWNLOADING": 18.0,
    "PREPROCESSING": 32.0,
    "PROCESSING": 58.0,
    "ANALYZING": 78.0,
    "POSTPROCESSING": 90.0,
    "COMPLETED": 100.0,
    "FAILED": 100.0,
    "CANCELLED": 100.0,
}


def append_log(job: ProcessingJob, message: str, level: str = "INFO", **extra: Any) -> None:
    job.logs = list(job.logs or []) + [
        {
            "ts": datetime.now(timezone.utc).isoformat(),
            "level": level,
            "message": message,
            "correlation_id": job.correlation_id,
            **extra,
        }
    ]


def transition(session: Session, job: ProcessingJob, status: str, message: str) -> None:
    # Refresh the status so an external cancellation request is honoured even
    # though the worker holds its own ORM instance.
    session.refresh(job, attribute_names=["status"])
    if job.status == "CANCELLED" and status not in TERMINAL_STATES:
        raise _Cancelled()
    job.status = status
    job.progress = PROGRESS.get(status, job.progress)
    job.current_stage = status
    append_log(job, message)
    if status == "VALIDATING" and job.started_at is None:
        job.started_at = utcnow()
    if status in TERMINAL_STATES:
        job.finished_at = utcnow()
    session.commit()


class _Cancelled(Exception):
    pass


def _load_products(session: Session, product_ids: list[str]) -> tuple[list[Product], list[Observation]]:
    products = session.scalars(
        select(Product)
        .options(selectinload(Product.observation))
        .where(Product.id.in_(product_ids))
    ).all()
    by_id = {p.id: p for p in products}
    ordered = [by_id[pid] for pid in product_ids if pid in by_id]
    observations = [p.observation for p in ordered if p.observation is not None]
    return ordered, observations


def _materialize_inputs(
    products: list[Product], session: Session
) -> list[InputProduct]:
    store = get_object_store()
    inputs: list[InputProduct] = []
    for product in products:
        obs = product.observation
        if product.object_uri is None:
            from app.core.errors import ValidationError

            raise ValidationError(f"Product {product.product_id} has no object URI")
        path = store.materialize(product.object_uri)
        dataset = session.get(Dataset, obs.dataset_id) if obs else None
        inputs.append(
            InputProduct(
                db_id=product.id,
                product_id=product.product_id,
                product_type=product.product_type,
                path=path,
                provider=product.provider,
                acquisition_start=obs.acquisition_start.isoformat() if obs and obs.acquisition_start else None,
                acquisition_end=obs.acquisition_end.isoformat() if obs and obs.acquisition_end else None,
                frequency_band=obs.frequency_band if obs else None,
                frequency_hz=obs.frequency_hz if obs else None,
                polarization=obs.polarization if obs else None,
                wavelength_m=obs.wavelength_m if obs else None,
                units=obs.units if obs else None,
                crs=obs.crs if obs else None,
                bbox=obs.bbox if obs else [],
                dataset_id=dataset.dataset_id if dataset else None,
                observation_id=obs.id if obs else None,
                is_demo=product.is_demo,
                tags=dict((product.normalized_metadata or {}).get("extra", {}).get("raster", {}).get("tags", {}) or {}),
            )
        )
    return inputs


def execute_job(job_id: str, *, claimed: bool = False) -> str:
    """Execute a queued job synchronously in a fresh session. Returns final status.

    ``claimed`` is set by the standalone worker after an atomic claim. The API
    and demo seeder call with the default and therefore only run QUEUED jobs.
    """
    settings = get_settings()
    with session_scope() as session:
        job = session.get(ProcessingJob, job_id)
        if job is None:
            raise ValueError(f"Job {job_id} not found")
        if job.status in TERMINAL_STATES:
            return job.status
        if job.status != "QUEUED" and not (claimed and job.status == "CLAIMED"):
            # A worker must not steal an actively running job.
            return job.status
        token = correlation_id_var.set(job.correlation_id)
        run: ProcessingRun | None = None
        try:
            job.started_at = utcnow()
            transition(session, job, "VALIDATING", "Validating AOI, product types and processing parameters")
            products, observations = _load_products(session, list(job.product_ids))
            if len(products) != len(job.product_ids):
                from app.core.errors import ValidationError

                raise ValidationError("One or more selected products no longer exist")
            processor_cls = PROCESSORS.get(job.analysis_type)
            if processor_cls is None:
                from app.core.errors import ValidationError

                raise ValidationError(f"Unknown analysis type '{job.analysis_type}'")
            processor = processor_cls()
            aoi = session.get(AOI, job.aoi_id) if job.aoi_id else None
            transition(session, job, "DOWNLOADING", "Materializing inputs from object storage")
            inputs = _materialize_inputs(products, session)
            is_demo = all(p.is_demo for p in products)
            # Prequeue a result ID so artifacts are namespaced by an immutable run.
            from app.db.base import new_uuid

            result_id = new_uuid()
            ctx = ProcessContext(
                job_id=job.id,
                result_id=result_id,
                aoi_geometry=aoi.geometry if aoi else {"type": "Polygon", "coordinates": []},
                aoi_name=aoi.name if aoi else "AOI",
                inputs=inputs,
                parameters=dict(job.parameters or {}),
                store=get_object_store(),
                is_demo=is_demo,
                request_id=job.correlation_id,
            )
            processor.validate(ctx)
            transition(session, job, "PREPROCESSING", "Preprocessing and aligning observations")
            provenance = build_provenance(
                algorithm=processor.algorithm,
                algorithm_version=processor.algorithm_version,
                parameters=dict(job.parameters or {}),
                dataset_ids=sorted({i.dataset_id for i in inputs if i.dataset_id}),
                observation_ids=[o.id for o in observations],
                product_ids=[p.product_id for p in products],
                crs="EPSG:4326",
                units=processor.units,
                request_id=job.correlation_id,
                aoi_id=aoi.id if aoi else None,
                extra={
                    "analysis_type": job.analysis_type,
                    "isce3": get_isce3_adapter().health(),
                    "processing_modes": ["CPU"],
                    "demo_mode": is_demo,
                },
            )
            run = ProcessingRun(
                job_id=job.id,
                analysis_type=job.analysis_type,
                algorithm=processor.algorithm,
                algorithm_version=processor.algorithm_version,
                parameters=dict(job.parameters or {}),
                input_product_ids=[p.id for p in products],
                observation_ids=[o.id for o in observations],
                dataset_ids=sorted({i.dataset_id for i in inputs if i.dataset_id}),
                crs="EPSG:4326",
                units=processor.units,
                code_version=settings.code_version,
                provenance=provenance,
                status="RUNNING",
                started_at=utcnow(),
            )
            session.add(run)
            session.commit()

            transition(session, job, "PROCESSING", f"Running {processor.algorithm} ({processor.algorithm_version})")
            output = processor.run(ctx)
            transition(session, job, "ANALYZING", "Persisting measurements, confidence and evidence tiers")
            result = AnalysisResult(
                id=result_id,
                run_id=run.id,
                job_id=job.id,
                aoi_id=aoi.id if aoi else None,
                result_type=output.result_type,
                summary=output.summary,
                statistics=output.statistics,
                artifacts={},
                layer_metadata=output.layers,
                units=output.units,
                confidence=output.confidence,
                uncertainty=output.uncertainty,
                is_demo=is_demo,
            )
            session.add(result)
            session.flush()
            for spec in output.features:
                session.add(
                    SARFeature(
                        result_id=result.id,
                        feature_type=spec.feature_type,
                        geometry=spec.geometry,
                        value=spec.value,
                        unit=spec.unit,
                        uncertainty=spec.uncertainty,
                        confidence=spec.confidence,
                        properties=spec.properties,
                    )
                )
            if output.change_map:
                session.add(
                    ChangeMap(
                        result_id=result.id,
                        aoi_id=aoi.id if aoi else None,
                        method=str(output.change_map.get("method")),
                        threshold=output.change_map.get("threshold"),
                        change_fraction=float(output.change_map.get("change_fraction") or 0.0),
                        statistics=output.change_map.get("statistics") or {},
                        artifact_uri=output.layers.get("change_mask", {}).get("raster_uri"),
                        confidence=output.change_map.get("confidence"),
                        is_demo=is_demo,
                    )
                )
            session.add(
                ConfidenceScore(
                    entity_type="analysis_result",
                    entity_id=result.id,
                    score=float(output.confidence or 0.0),
                    method=f"{processor.algorithm}_confidence",
                    components={"mean_detection_confidence": output.confidence},
                )
            )
            if output.uncertainty is not None:
                session.add(
                    UncertaintyEstimate(
                        entity_type="analysis_result",
                        entity_id=result.id,
                        value=float(output.uncertainty),
                        unit=output.units,
                        method="robust_mad_or_coherence_phase_variance",
                        components={"analysis_type": job.analysis_type},
                    )
                )
            session.flush()
            events = build_events(
                session,
                output=output,
                result=result,
                run=run,
                job=job,
                aoi=aoi,
                products=products,
                observations=observations,
            )
            for spec in output.timeseries:
                session.add(
                    TimeSeries(
                        aoi_id=aoi.id if aoi else None,
                        result_id=result.id,
                        event_id=None,
                        series_type=spec.series_type,
                        unit=spec.unit,
                        points=spec.points,
                        trend=spec.trend,
                        change_points=spec.change_points,
                        gaps=spec.gaps,
                        confidence=spec.confidence,
                        is_demo=is_demo,
                    )
                )
            for event in events:
                session.add(
                    ConfidenceScore(
                        entity_type="change_event",
                        entity_id=event.id,
                        score=float(event.confidence or 0.0),
                        method=f"{processor.algorithm}_event_confidence",
                        components={"severity": event.severity, "area_m2": event.area_m2},
                    )
                )
                if event.uncertainty is not None:
                    session.add(
                        UncertaintyEstimate(
                            entity_type="change_event",
                            entity_id=event.id,
                            value=float(event.uncertainty),
                            unit=event.magnitude_unit or output.units,
                            method="feature_uncertainty",
                            components={},
                        )
                    )
            result.artifacts = {name: meta.get("raster_uri") for name, meta in output.layers.items()}
            result.layer_metadata = {
                **output.layers,
                "provenance": {
                    "run_id": run.id,
                    "code_version": settings.code_version,
                    "algorithm": processor.algorithm,
                    "algorithm_version": processor.algorithm_version,
                    "parameters": job.parameters,
                },
                "limitations": output.warnings,
                "isce3": get_isce3_adapter().health(),
            }
            transition(session, job, "POSTPROCESSING", "Linking geospatial context and potential exposure")
            for event in events:
                try:
                    correlate_event_context(session, event)
                    compute_exposures(session, event)
                except Exception as exc:  # noqa: BLE001 - context is optional
                    append_log(job, f"Context linkage warning: {exc}", level="WARNING")
            run.status = "COMPLETED"
            run.finished_at = utcnow()
            session.add(
                AuditLog(
                    actor=job.requested_by,
                    action="analysis.completed",
                    entity_type="processing_job",
                    entity_id=job.id,
                    correlation_id=job.correlation_id,
                    detail={"result_id": result.id, "events": len(events), "demo": is_demo},
                )
            )
            transition(
                session,
                job,
                "COMPLETED",
                f"Completed: {len(events)} event(s), {len(output.features)} feature(s), {len(output.layers)} layer(s)",
            )
            return "COMPLETED"
        except _Cancelled:
            job.status = "CANCELLED"
            job.current_stage = "CANCELLED"
            job.progress = 100.0
            job.finished_at = utcnow()
            append_log(job, "Job cancelled by request", level="WARNING")
            if run:
                run.status = "CANCELLED"
                run.finished_at = utcnow()
            session.commit()
            return "CANCELLED"
        except Exception as exc:  # noqa: BLE001 - job failure must be persisted, not silent
            logger.exception("Job %s failed", job_id)
            job.status = "FAILED"
            job.current_stage = "FAILED"
            job.progress = 100.0
            job.error = str(exc)
            job.finished_at = utcnow()
            append_log(job, f"Failed: {exc}", level="ERROR")
            if run:
                run.status = "FAILED"
                run.finished_at = utcnow()
            session.add(
                AuditLog(
                    actor=job.requested_by,
                    action="analysis.failed",
                    entity_type="processing_job",
                    entity_id=job.id,
                    correlation_id=job.correlation_id,
                    detail={"error": str(exc), "traceback": traceback.format_exc(limit=6)},
                )
            )
            session.commit()
            return "FAILED"
        finally:
            correlation_id_var.reset(token)
